//! RQ8 Q2 latency slice 1 (docs/rq8.md "Q2 measurement slice 1"): MODELED responder-delay
//! scenarios. These are deterministic values computed from explicitly **assumed** inputs
//! (query count, cache hit/miss, serial vs parallel, an assumed per-query `rtt_ms`). They are
//! modeled, **not measured**: there is no timing, no `sleep`, and no network here — just
//! arithmetic over the assumptions. The measured per-call CPU elapsed time is reported
//! separately by `bench.rs` (`results/bench_<UTC>.{md,json}`); real end-to-end network latency
//! is unmeasured. Gated against `tests/cases/rq8_latency_cases.toml` (owner-reviewed).

use serde_json::{json, Value};

use super::cases::CaseLabel;

pub const RQ8_LATENCY_CASES_PATH: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/tests/cases/rq8_latency_cases.toml"
);

pub const RQ8_LATENCY_CASE_IDS: &[&str] = &["QL01", "QL02", "QL03", "QL04", "QL05", "QL06"];

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Mode {
    Serial,
    Parallel,
    /// No responder query at all (e.g. a stapled owner-signed freshness token).
    None,
}

impl Mode {
    fn as_str(self) -> &'static str {
        match self {
            Mode::Serial => "serial",
            Mode::Parallel => "parallel",
            Mode::None => "none",
        }
    }
}

/// One modeled scenario: all inputs are assumed, not measured.
#[derive(Clone, Copy, Debug)]
struct Scenario {
    queries: u64,
    misses: u64,
    mode: Mode,
    rtt_ms: u64,
}

/// The modeled responder-delay formula (docs/rq8.md Q2 slice 1), fixed before computing:
/// stapled (no query) → 0; serial → `misses * rtt`; parallel → one round-trip if any miss.
fn responder_delay_ms(s: Scenario) -> u64 {
    if s.queries == 0 {
        return 0;
    }
    match s.mode {
        Mode::Serial => s.misses * s.rtt_ms,
        Mode::Parallel => {
            if s.misses > 0 {
                s.rtt_ms
            } else {
                0
            }
        }
        Mode::None => 0,
    }
}

fn observation(s: Scenario) -> String {
    format!(
        "queries={} misses={} mode={} rtt_ms={} responder_delay_ms={}",
        s.queries,
        s.misses,
        s.mode.as_str(),
        s.rtt_ms,
        responder_delay_ms(s),
    )
}

fn scenario(id: &str) -> Option<Scenario> {
    let s = |queries, misses, mode, rtt_ms| Scenario {
        queries,
        misses,
        mode,
        rtt_ms,
    };
    Some(match id {
        "QL01" => s(3, 3, Mode::Serial, 50),
        "QL02" => s(3, 3, Mode::Parallel, 50),
        "QL03" => s(3, 0, Mode::Serial, 50),
        "QL04" => s(3, 1, Mode::Serial, 50),
        "QL05" => s(3, 1, Mode::Parallel, 50),
        "QL06" => s(0, 0, Mode::None, 50),
        _ => return None,
    })
}

/// Run RQ8 latency case `id`; `None` for an unknown id.
pub fn run(id: &str) -> Option<String> {
    scenario(id).map(observation)
}

pub struct LatencyRow {
    pub label: CaseLabel,
    pub actual: String,
}

pub fn run_all(labels: &[CaseLabel]) -> Vec<LatencyRow> {
    labels
        .iter()
        .map(|l| LatencyRow {
            label: l.clone(),
            actual: run(&l.id).unwrap_or_else(|| format!("no runner for {}", l.id)),
        })
        .collect()
}

pub fn render_markdown(rows: &[LatencyRow]) -> String {
    let matched = rows.iter().filter(|r| r.actual == r.label.expected).count();
    let mut out = String::from(
        "# RQ8 Q2 latency slice 1 — modeled responder-delay scenarios (generated)\n\n",
    );
    out.push_str("Generated by `cargo run --release --bin eval`. Labels (owner-reviewed as ");
    out.push_str("modeled arithmetic) come from `tests/cases/rq8_latency_cases.toml`; method in ");
    out.push_str("`docs/rq8.md`. These are **modeled** values from assumed inputs (an assumed ");
    out.push_str("`rtt_ms`, not a measured RTT); no timing, no `sleep`, no network. Parallel and ");
    out.push_str("stapled are hypothetical scenarios, not implemented verifier paths. The ");
    out.push_str("**measured** per-call CPU elapsed is in the bench results ");
    out.push_str(
        "(`results/bench_<UTC>.md`); real **end-to-end** network latency is unmeasured.\n\n",
    );
    out.push_str(&format!(
        "Matched {matched}/{} reviewed scenarios.\n\n",
        rows.len()
    ));
    out.push_str("| ID | Label status | Note | Expected | Actual | Match |\n| --- | --- | --- | --- | --- | --- |\n");
    for r in rows {
        out.push_str(&format!(
            "| {} | {} | {} | `{}` | `{}` | {} |\n",
            r.label.id,
            r.label.label_status,
            r.label.note,
            r.label.expected,
            r.actual,
            if r.actual == r.label.expected {
                "yes"
            } else {
                "**NO**"
            }
        ));
    }
    out
}

pub fn render_json(rows: &[LatencyRow]) -> Value {
    json!({
        "matched": rows.iter().filter(|r| r.actual == r.label.expected).count(),
        "total": rows.len(),
        "cases": rows.iter().map(|r| json!({
            "id": r.label.id,
            "label_status": r.label.label_status,
            "note": r.label.note,
            "expected": r.label.expected,
            "actual": r.actual,
            "match": r.actual == r.label.expected,
        })).collect::<Vec<_>>(),
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn serial_scales_with_misses_parallel_bounded_by_one() {
        let serial = Scenario {
            queries: 3,
            misses: 3,
            mode: Mode::Serial,
            rtt_ms: 50,
        };
        let parallel = Scenario {
            mode: Mode::Parallel,
            ..serial
        };
        assert_eq!(responder_delay_ms(serial), 150);
        assert_eq!(responder_delay_ms(parallel), 50);
    }

    #[test]
    fn no_miss_and_stapled_are_zero() {
        assert_eq!(
            responder_delay_ms(Scenario {
                queries: 3,
                misses: 0,
                mode: Mode::Serial,
                rtt_ms: 50
            }),
            0
        );
        assert_eq!(
            responder_delay_ms(Scenario {
                queries: 0,
                misses: 0,
                mode: Mode::None,
                rtt_ms: 50
            }),
            0
        );
    }
}
